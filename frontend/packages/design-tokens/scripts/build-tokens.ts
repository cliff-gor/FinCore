/**
 * Generates platform theme files from the single token source (master spec §32.9):
 *  - build/tailwind-theme.css  Tailwind v4 `@theme` variables (+ dark overrides) for the web apps
 *  - build/nativewind.js       Tailwind theme extension consumed by apps/mobile/tailwind.config.js
 * Run with `node scripts/build-tokens.ts` (Node >= 22.18 strips TypeScript types natively).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  fontFamilies,
  motion,
  palette,
  radius,
  semanticDark,
  semanticLight,
  shadows,
  spacing,
  typeScale,
  type SemanticColors,
} from '../src/index.ts';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'build');
const header = '/* GENERATED by packages/design-tokens/scripts/build-tokens.ts — do not edit. */';

const semanticVars = (colors: SemanticColors, indent: string): string =>
  Object.entries(colors)
    .map(([name, value]) => `${indent}--fc-${name}: ${value};`)
    .join('\n');

function tailwindTheme(): string {
  const lines: string[] = [header, '', '@theme {'];
  for (const [name, value] of Object.entries(palette)) lines.push(`  --color-${name}: ${value};`);
  lines.push(`  --font-display: ${fontFamilies.display.join(', ')};`);
  lines.push(`  --font-sans: ${fontFamilies.sans.join(', ')};`);
  lines.push(`  --font-serif: ${fontFamilies.serif.join(', ')};`);
  for (const [name, style] of Object.entries(typeScale)) {
    lines.push(`  --text-${name}: ${style.size / 16}rem;`);
    lines.push(`  --text-${name}--line-height: ${style.lineHeight / 16}rem;`);
    lines.push(`  --text-${name}--font-weight: ${style.weight};`);
  }
  for (const [name, value] of Object.entries(radius)) lines.push(`  --radius-${name}: ${value}px;`);
  for (const [name, value] of Object.entries(shadows)) lines.push(`  --shadow-${name}: ${value};`);
  for (const [name, value] of Object.entries(motion.duration)) {
    lines.push(`  --duration-${name}: ${value}ms;`);
  }
  lines.push(`  --ease-standard: ${motion.easing.standard};`);
  lines.push('}', '', '@theme inline {');
  for (const name of Object.keys(semanticLight))
    lines.push(`  --color-${name}: var(--fc-${name});`);
  lines.push('}', '', ':root {', semanticVars(semanticLight, '  '), '}', '');
  lines.push("[data-theme='dark'] {", semanticVars(semanticDark, '  '), '}', '');
  return lines.join('\n');
}

function nativewindTheme(): string {
  const px = (record: Record<string | number, number>): Record<string, string> =>
    Object.fromEntries(Object.entries(record).map(([k, v]) => [k, `${v}px`]));
  const theme = {
    colors: { ...palette, ...semanticLight, dark: semanticDark },
    spacing: px(spacing),
    borderRadius: px(radius),
    fontFamily: {
      display: [...fontFamilies.display],
      sans: [...fontFamilies.sans],
      serif: [...fontFamilies.serif],
    },
    fontSize: Object.fromEntries(
      Object.entries(typeScale).map(([name, s]) => [
        name,
        [`${s.size}px`, { lineHeight: `${s.lineHeight}px`, fontWeight: String(s.weight) }],
      ]),
    ),
  };
  return `${header}\n/** @type {Record<string, unknown>} */\nmodule.exports = ${JSON.stringify(theme, null, 2)};\n`;
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tailwind-theme.css'), tailwindTheme());
writeFileSync(join(outDir, 'nativewind.js'), nativewindTheme());
// nativewind.js is CommonJS (tailwind.config.js requires it) while this package is "type": "module".
writeFileSync(join(outDir, 'package.json'), '{ "type": "commonjs" }\n');
console.log(`design tokens written to ${outDir}`);
